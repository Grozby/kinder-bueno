"""Case eval (#73): run the case analysis on the example business models and compare with eval/cases.yaml.

Read-only: no case row is written. The needs are pinned in the gold file, so a change to matching or scoring
is measured on the same input (the LLM's wording of the needs varies between runs). A case without pinned
needs has them read by Apertus; the report prints them so they can be pinned.

Metrics per case:
- match recall: `must_match` entities that count in the score (a claim matched a need).
- in references: `must_match` entities among the 25 references at all (a miss here is a search miss, not
  a matching miss).
- false matches: `must_not_match` entities that count in the score.
- score in range: the overall score within the expected range.
"""

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import psycopg
import yaml

from navigator.cases.analysis import CaseInfo, Scored, score_needs
from navigator.cases.store import pdf_text
from navigator.evaluation.gold import Expected, matches


@dataclass(frozen=True)
class GoldCase:
    id: str
    pdf: str
    score: tuple[int, int]
    needs: list[str]
    must_match: list[Expected]
    must_not_match: list[Expected]


def load_cases(path: Path) -> list[GoldCase]:
    def entities(rows: list | None) -> list[Expected]:
        return [Expected(name=e["name"], type=e["type"], url=e.get("url", "")) for e in rows or []]

    return [
        GoldCase(
            id=c["id"], pdf=str(path.parent / c["pdf"]), score=tuple(c["score"]), needs=c.get("needs") or [],
            must_match=entities(c.get("must_match")), must_not_match=entities(c.get("must_not_match")),
        )
        for c in yaml.safe_load(path.read_text())["cases"]
    ]


@dataclass
class Outcome:
    case: GoldCase
    needs: list[str]
    scored: Scored

    def _hits(self, expected: list[Expected], matched_only: bool) -> list[Expected]:
        pool = [(r.type, r.name) for r in self.scored.results if not matched_only or self.scored.matches.get(r.entity_id)]
        return [e for e in expected if any(matches(e, t, n) for t, n in pool)]

    @property
    def matched(self) -> list[Expected]:
        return self._hits(self.case.must_match, matched_only=True)

    @property
    def in_references(self) -> list[Expected]:
        return self._hits(self.case.must_match, matched_only=False)

    @property
    def false_matches(self) -> list[Expected]:
        return self._hits(self.case.must_not_match, matched_only=True)

    @property
    def score_ok(self) -> bool:
        low, high = self.case.score
        return low <= self.scored.score <= high

    @property
    def uncovered(self) -> list[str]:
        covered = {m.need for ms in self.scored.matches.values() for m in ms}
        return [n for n in self.needs if n not in covered]


def evaluate_case(
    conn: psycopg.Connection, case: GoldCase, read: Callable[[str], CaseInfo],
    embed: Callable[[str], np.ndarray], embed_many: Callable[[list[str]], np.ndarray],
    rerank: Callable[[list[tuple[str, str]]], np.ndarray],
) -> Outcome:
    needs = case.needs or read(pdf_text(Path(case.pdf).read_bytes())).needs
    return Outcome(case, needs, score_needs(conn, needs, embed, embed_many, rerank))


def _share(part: int, whole: int) -> str:
    return f"{part}/{whole}" if whole else "–"


def report(outcomes: list[Outcome]) -> str:
    lines = [
        "# Case eval (#73)",
        "",
        "Generated by `navigator case-eval` from `eval/cases.yaml`. Needs are pinned there unless marked *read*.",
        "",
        "| Case | Score | Expected | Match recall | In references | False matches | Uncovered needs |",
        "|---|---|---|---|---|---|---|",
    ]
    for o in outcomes:
        low, high = o.case.score
        lines.append(
            f"| {o.case.id} | {o.scored.score} {'✓' if o.score_ok else '✗'} | {low}–{high} "
            f"| {_share(len(o.matched), len(o.case.must_match))} | {_share(len(o.in_references), len(o.case.must_match))} "
            f"| {len(o.false_matches)} | {len(o.uncovered)} of {len(o.needs)} |"
        )
    must = sum(len(o.case.must_match) for o in outcomes)
    lines += [
        "",
        (
            f"**Total:** match recall {_share(sum(len(o.matched) for o in outcomes), must)}, "
            f"in references {_share(sum(len(o.in_references) for o in outcomes), must)}, "
            f"false matches {sum(len(o.false_matches) for o in outcomes)}, "
            f"scores in range {sum(o.score_ok for o in outcomes)}/{len(outcomes)}."
        ),
    ]
    for o in outcomes:
        found = {e.name for e in o.in_references}
        pinned = "" if o.case.needs else " (*read*, not pinned)"
        lines += ["", f"## {o.case.id}", "", f"Needs{pinned}: " + "; ".join(o.needs), ""]
        lines += [f"- {row.criterion}: {row.score} — {row.rationale}" for row in o.scored.rows]
        missed = [e for e in o.case.must_match if e not in o.matched]
        if missed:
            lines.append("- Missed: " + "; ".join(
                f"{e.name} ({'in references, no matching claim' if e.name in found else 'not in references'})"
                for e in missed))
        if o.false_matches:
            lines.append("- False matches: " + "; ".join(e.name for e in o.false_matches))
        lines += ["", "| Matched entity | Type | Need | Claim | Reranker | Cosine |", "|---|---|---|---|---|---|"]
        for r in o.scored.results:
            for m in o.scored.matches.get(r.entity_id, []):
                via = f" (via {m.via})" if m.via else ""
                lines.append(f"| {r.name} | {r.type} | {m.need} | {m.value}{via} | {m.score:.2f} | {m.sim:.2f} |")
    return "\n".join(lines) + "\n"
